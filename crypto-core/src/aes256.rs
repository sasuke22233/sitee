/// Раундовые константы ключевого расписания.
const RCON: [u8; 15] = [
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36, 0x6c, 0xd8, 0xab, 0x4d,
];

/// Число слов расписания: 4 * (Nr + 1) = 60 при Nr = 14.
pub const ROUND_KEYS: usize = 60;

/// Расширение 256-битного ключа в 60 32-битных раундовых ключей.
pub fn key_expansion(key: &[u8; 32]) -> [u32; ROUND_KEYS] {
    const NK: usize = 8;
    const NR: usize = 14;
    let mut w = [0u32; ROUND_KEYS];
    for i in 0..NK {
        w[i] = u32::from_be_bytes([key[4 * i], key[4 * i + 1], key[4 * i + 2], key[4 * i + 3]]);
    }
    for i in NK..4 * (NR + 1) {
        let mut temp = w[i - 1];
        if i % NK == 0 {
            temp = temp.rotate_left(8);
            temp = sub_word(temp) ^ ((RCON[i / NK] as u32) << 24);
        } else if i % NK == 4 {
            temp = sub_word(temp);
        }
        w[i] = w[i - NK] ^ temp;
    }
    w
}

fn sub_word(w: u32) -> u32 {
    ((SBOX[(w >> 24) as usize & 0xff] as u32) << 24)
        | ((SBOX[(w >> 16) as usize & 0xff] as u32) << 16)
        | ((SBOX[(w >> 8) as usize & 0xff] as u32) << 8)
        | (SBOX[w as usize & 0xff] as u32)
}

/// Шифрование одного 128-битного блока.
pub fn encrypt_block(rk: &[u32; ROUND_KEYS], block: &[u8; 16]) -> [u8; 16] {
    // Состояние — по столбцам: s[r + 4*c].
    let mut s = [[0u8; 4]; 4];
    for r in 0..4 {
        for c in 0..4 {
            s[r][c] = block[r + 4 * c];
        }
    }
    add_round_key(&mut s, rk, 0);
    for round in 1..=13 {
        sub_bytes(&mut s);
        shift_rows(&mut s);
        mix_columns(&mut s);
        add_round_key(&mut s, rk, round);
    }
    sub_bytes(&mut s);
    shift_rows(&mut s);
    add_round_key(&mut s, rk, 14);
    let mut out = [0u8; 16];
    for r in 0..4 {
        for c in 0..4 {
            out[r + 4 * c] = s[r][c];
        }
    }
    out
}

fn add_round_key(s: &mut [[u8; 4]; 4], rk: &[u32; ROUND_KEYS], round: usize) {
    for c in 0..4 {
        let w = rk[round * 4 + c];
        s[0][c] ^= (w >> 24) as u8;
        s[1][c] ^= (w >> 16) as u8;
        s[2][c] ^= (w >> 8) as u8;
        s[3][c] ^= w as u8;
    }
}

fn sub_bytes(s: &mut [[u8; 4]; 4]) {
    for r in 0..4 {
        for c in 0..4 {
            s[r][c] = SBOX[s[r][c] as usize];
        }
    }
}

fn shift_rows(s: &mut [[u8; 4]; 4]) {
    for r in 1..4 {
        let row = s[r];
        for c in 0..4 {
            s[r][c] = row[(c + r) % 4];
        }
    }
}

/// Умножение на x в GF(2^8) по модулю x^8 + x^4 + x^3 + x + 1.
fn xtime(a: u8) -> u8 {
    let shifted = a << 1;
    if a & 0x80 != 0 {
        shifted ^ 0x1b
    } else {
        shifted
    }
}

fn mix_columns(s: &mut [[u8; 4]; 4]) {
    for c in 0..4 {
        let a = s[0][c];
        let b = s[1][c];
        let cc = s[2][c];
        let d = s[3][c];
        s[0][c] = xtime(a) ^ (xtime(b) ^ b) ^ cc ^ d;
        s[1][c] = a ^ xtime(b) ^ (xtime(cc) ^ cc) ^ d;
        s[2][c] = a ^ b ^ xtime(cc) ^ (xtime(d) ^ d);
        s[3][c] = (xtime(a) ^ a) ^ b ^ cc ^ xtime(d);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::to_hex;

    #[test]
    fn fips197_appendix_c3() {
        // AES-256, ключ 00..00, блок 00..00 → dc95c078a2408989ad48a21492842087.
        let rk = key_expansion(&[0u8; 32]);
        let ct = encrypt_block(&rk, &[0u8; 16]);
        assert_eq!(to_hex(&ct), "dc95c078a2408989ad48a21492842087");
    }

    #[test]
    fn sbox_first_bytes() {
        assert_eq!(&SBOX[0..16], b"\x63\x7c\x77\x7b\xf2\x6b\x6f\xc5\x30\x01\x67\x2b\xfe\xd7\xab\x76");
        assert_eq!(SBOX[0x53], 0xed);
    }
}
